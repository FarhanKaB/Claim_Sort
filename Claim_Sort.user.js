    const DEMOTE_SET = new Set(DEMOTE_LIST.map(c => c.trim().toUpperCase()));
    const DEMOTE_RANK = new Map(DEMOTE_LIST.map((code, idx) => [code.trim().toUpperCase(), idx]));

    // ─── Row helper ──────────────────────────────────────────
    // Real ICD rows carry ng-repeat="icd in ICDCodes..."; the trailing
    // "add new ICD" row does not, so this selector already excludes it.
    function getICDRows() {
        return Array.from(document.querySelectorAll('#icdTable tbody tr[ng-repeat]'));
    }

    // ─── Sort logic ──────────────────────────────────────────
    // Grab the Angular scope off the first ICD row, sort scope.ICDCodes
    // in place inside $apply. Angular re-renders the "#" column and
    // code/name cells automatically via ng-repeat.
    function sortICD() {
        const rows = getICDRows();
        if (!rows.length) return;

        const s = angular.element(rows[0]).scope();
        if (!s || !Array.isArray(s.ICDCodes)) {
            console.warn('ECW ICD Sort: could not find scope.ICDCodes');
            return;
        }

        s.$apply(() => {
            s.ICDCodes.sort((a, b) => {
                const aCode = (a.code || '').trim().toUpperCase();
                const bCode = (b.code || '').trim().toUpperCase();
                const aDemoted = DEMOTE_SET.has(aCode);
                const bDemoted = DEMOTE_SET.has(bCode);

                if (aDemoted && bDemoted) {
                    return DEMOTE_RANK.get(aCode) - DEMOTE_RANK.get(bCode);
                }
                if (aDemoted !== bDemoted) {
                    return aDemoted ? 1 : -1; // demoted codes sink to the bottom
                }
                return 0; // Array.prototype.sort is stable: keeps original order otherwise
            });
        });
    }

